// ĞIGI GIVØ — 12-factor ranking verification (Part 4 gate).
//
// Runs the REAL engine pipeline (market generator + selector) end-to-end,
// without any network or database, and asserts the API-facing contract:
//
//   1. The selection still exposes `top10` (NOT renamed to `markets`).
//   2. Every pick in top10 carries a NEW additive `factors` object and a
//      `compositeScore` — and no existing field was removed or renamed.
//   3. The factor breakdown uses exactly the 12 canonical factor labels,
//      values are 0..1, and unavailable factors are excluded (their weight
//      redistributed) rather than simulated.
//   4. The EngineResult shape consumed by the UI (top10 array inside the
//      prediction payload) is unchanged.
//
// Run:  npx tsx scripts/verify-12factors.ts

import { buildMatchContext } from "../src/lib/engine/context";
import { buildLambdas } from "../src/lib/engine/lambdas";
import { MarketEngine } from "../src/lib/engine/markets";
import {
  selectTopPicks,
  FACTOR_LABELS,
  RANKING_WEIGHTS,
  type FactorKey,
} from "../src/lib/engine/selector";
import type { Market, PredictInput } from "../src/lib/engine/types";
import {
  emptyCanonicalMatchStats,
  STAT_FIELDS,
  type CanonicalMatchStats,
} from "../src/lib/data/types";

const KNOWN_LABELS = new Set(Object.values(FACTOR_LABELS));
const REQUIRED_EXISTING_FIELDS: Array<keyof Market> = [
  "id", "name", "family", "selection", "hitRate", "ciLower", "ciUpper",
  "ciWidth", "fairOddsBest", "fairOddsWorst", "mqs", "grade", "confidence",
  "disagreementIndex", "rejected", "niche",
];

let failures = 0;
function assert(cond: boolean, label: string): void {
  if (cond) {
    console.log(`  ✓ ${label}`);
  } else {
    failures++;
    console.error(`  ✗ ${label}`);
  }
}

// ─── Deterministic real-engine fixture (no network, no DB) ───────────────────
const input: PredictInput = {
  auto: true,
  match: "Arsenal vs Chelsea",
  league: "Premier League",
  date: "2026-08-29",
};
const { match, home, away } = buildMatchContext(input);
const lam = buildLambdas(match, home, away);
const engine = new MarketEngine(match, lam);
const markets = engine.buildAll().filter((m) => !m.rejected);

/** Canonical stats shaped exactly like the aggregator's real output. */
function aggregatorStats(): CanonicalMatchStats {
  const s = emptyCanonicalMatchStats({
    leagueSlug: "eng.1",
    eventId: "verify-12factors",
    homeTeam: input.match.split(" vs ")[0],
    awayTeam: input.match.split(" vs ")[1],
    date: input.date,
  });
  // Realistic partial aggregator payload (first-wins merge result).
  for (const key of STAT_FIELDS) {
    (s.home[key] as number | null) = 5;
    (s.away[key] as number | null) = 4;
  }
  s.home.xg = 1.9; s.away.xg = 1.1;
  s.home.goals = 2; s.away.goals = 1;
  s.home.corners = 6; s.away.corners = 4;
  s.home.shotsOnTarget = 6; s.away.shotsOnTarget = 3;
  s.home.cleanSheet = false; s.away.cleanSheet = false;
  s.metadata.source = "API-Football";
  return s;
}

console.log(`\n12-factor verification — ${markets.length} qualified markets generated by the real engine`);

// ── Check 0: weight table integrity ─────────────────────────────────────────
console.log("\n[0] Balanced weight table");
const weightKeys = Object.keys(RANKING_WEIGHTS) as FactorKey[];
assert(weightKeys.length === 12, "exactly 12 ranking factors");
const weightSum = weightKeys.reduce((sum, k) => sum + RANKING_WEIGHTS[k], 0);
assert(Math.abs(weightSum - 1.0) < 1e-9, `weights sum to 100% (Σ=${weightSum.toFixed(4)})`);

// ── Check 1: selection shape (no breaking renames) ──────────────────────────
console.log("\n[1] API selection shape — top10 intact");
const withStats = selectTopPicks(markets, lam, match.homeTeam, match.awayTeam, undefined, {
  stats: aggregatorStats(),
  context: { leagueSlug: "eng.1" },
});
assert(Array.isArray(withStats.top10), "selection.top10 is an array");
assert(withStats.top10.length > 0, `top10 is non-empty (${withStats.top10.length} picks)`);
assert(!("markets" in withStats), "no `markets` rename on the selection result");

// ── Check 2: additive factor fields on every top10 pick ─────────────────────
console.log("\n[2] factors + compositeScore attached (additive, non-breaking)");
for (const pick of withStats.top10) {
  assert(typeof pick.factors === "object" && pick.factors !== null, `${pick.name} → factors object present`);
  assert(typeof pick.compositeScore === "number", `${pick.name} → compositeScore present (${pick.compositeScore})`);
}
const sample = withStats.top10[0];
for (const field of REQUIRED_EXISTING_FIELDS) {
  assert(field in sample, `existing field preserved: ${String(field)}`);
}

// ── Check 3: factor label + value contract ──────────────────────────────────
console.log("\n[3] Factor breakdown contract");
let allLabelsKnown = true;
let allValuesInRange = true;
for (const pick of withStats.top10) {
  for (const [label, value] of Object.entries(pick.factors ?? {})) {
    if (!KNOWN_LABELS.has(label)) allLabelsKnown = false;
    if (typeof value !== "number" || value < 0 || value > 1) allValuesInRange = false;
  }
}
assert(allLabelsKnown, "every factor key is one of the 12 canonical labels");
assert(allValuesInRange, "every factor value is within 0..1");
assert(
  withStats.top10.some((p) => p.factors?.["Statistics all states filled"] !== undefined),
  "stats aggregator completeness factor present when canonical stats supplied",
);
const compositeInRange = withStats.top10.every(
  (p) => typeof p.compositeScore === "number" && p.compositeScore >= 0 && p.compositeScore <= 1,
);
assert(compositeInRange, "compositeScore within 0..1 for every pick");

// ── Check 4: unavailable factors excluded (weight redistributed, no fakes) ──
console.log("\n[4] Data-gap contract — exclusion, not simulation");
const noStats = selectTopPicks(markets, lam, match.homeTeam, match.awayTeam, undefined, {});
assert(Array.isArray(noStats.top10) && noStats.top10.length > 0, "top10 still returned without canonical stats");
const noStatsPick = noStats.top10[0];
assert(noStatsPick.factors !== undefined, "factors still attached without canonical stats");
assert(
  noStatsPick.factors?.["Statistics all states filled"] === undefined,
  "stats-only factor excluded (not simulated) when the aggregator has no data",
);

// ── Check 5: hit rate does not dominate the composite ───────────────────────
console.log("\n[5] Balance — hitRate/calibration cannot dominate");
assert(RANKING_WEIGHTS.stats <= 0.09, "Stats factor (contains hitRate) capped at 9%");
const maxSingleWeight = Math.max(...weightKeys.map((k) => RANKING_WEIGHTS[k]));
assert(maxSingleWeight <= 0.09, `no single factor weighs more than 9% (max=${maxSingleWeight})`);

// ── Check 6: API payload shape (what /api/match serialises) ─────────────────
console.log("\n[6] EngineResult payload shape (UI contract)");
const payloadShape = {
  top10: withStats.top10,
  top1: withStats.top10.slice(0, 1),
  top3: withStats.top10.slice(0, 3),
  top5: withStats.top10.slice(0, 5),
};
assert("top10" in payloadShape, "payload keeps `top10`");
const json = JSON.parse(JSON.stringify(payloadShape.top10[0])) as Record<string, unknown>;
assert(json.factors !== undefined, "serialised pick keeps `factors`");
assert(json.compositeScore !== undefined, "serialised pick keeps `compositeScore`");
assert(json.hitRate !== undefined && json.name !== undefined && json.id !== undefined,
  "serialised pick keeps all legacy display fields");

console.log(
  `\nSample pick: ${JSON.stringify(
    {
      id: sample.id,
      name: sample.name,
      hitRate: sample.hitRate,
      outcome: sample.outcome ?? "PENDING",
      factors: sample.factors,
      compositeScore: sample.compositeScore,
    },
    null,
    2,
  )}`,
);

if (failures > 0) {
  console.error(`\nFAILED — ${failures} assertion(s) failed.`);
  process.exit(1);
}
console.log("\nALL CHECKS PASSED — API contract intact, 12-factor breakdown live.");
